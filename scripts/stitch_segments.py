#!/usr/bin/env python3
"""
stitch_segments.py — Combine per-segment C++ sources into a single stitched file.

After cloud_segment_frontend.py produces the segment_replacements.json, this
script collects each segment's final C++ source (from compile_record.final_file)
and produces:

  1. <output_dir>/stitched/<benchmark>_stitched.cpp  — all segments combined
  2. <output_dir>/stitched/segment_XX.cpp             — individual segment sources
  3. <output_dir>/stitched/run_stitched.sh             — build-and-run helper script
  4. Updates the replacements JSON with stitching_output metadata

Usage:
  python stitch_segments.py --replacements-json <path> [--compile]
"""

import argparse
import json
import os
import shlex
import shutil
import subprocess
import sys
import textwrap
from collections import OrderedDict
from datetime import datetime, timezone
from pathlib import Path


def _read_segment_source(segment_result: dict) -> str | None:
    """Return the final C++ source for a segment, or None if unavailable."""
    cr = segment_result.get("compile_record") or {}
    final_file = cr.get("final_file")
    if final_file and os.path.isfile(final_file):
        return Path(final_file).read_text(encoding="utf-8", errors="replace")
    return None


def _segment_sort_key(seg_key: str) -> int:
    """Extract numeric index from 'segment_01' etc."""
    try:
        return int(seg_key.split("_")[-1])
    except ValueError:
        return 999


def _build_combined_source(
    segment_sources: dict[str, dict],
    benchmark_name: str,
) -> str:
    """
    Build a combined C++ file that contains all segment sources, separated by
    clear section markers.  Each segment's code is wrapped in
    ``#if SEGMENT_XX`` guards so the file can optionally be compiled one-segment-
    at-a-time with ``-DSEGMENT_01=1``, or compiled as a reference with all
    guards disabled (will not link, but serves as a single-file archive).
    """
    lines: list[str] = []
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines.append(f"// {'=' * 72}")
    lines.append(f"// Stitched benchmark: {benchmark_name}")
    lines.append(f"// Generated: {ts}")
    lines.append(f"// Segments:  {len(segment_sources)}")
    lines.append(f"//")
    lines.append(f"// This file is an archive of all per-segment C++ sources produced")
    lines.append(f"// by the cloud tuning pipeline.  Each segment is guarded with")
    lines.append(f"//     #if SEGMENT_XX")
    lines.append(f"// so you can compile a single segment with:")
    lines.append(f"//     g++ -DSEGMENT_01=1 -g -std=c++20 <this file> -o seg01")
    lines.append(f"// (assuming the framework headers are on the include path).")
    lines.append(f"//")

    for seg_key, info in segment_sources.items():
        idx = info["index"]
        target = info["target_file"]
        accuracy = info.get("policy_accuracy_pct", "N/A")
        lines.append(f"// Segment {idx:02d}: {target}   accuracy={accuracy}%")

    lines.append(f"// {'=' * 72}")
    lines.append("")

    for seg_key, info in segment_sources.items():
        idx = info["index"]
        guard = f"SEGMENT_{idx:02d}"
        target = info["target_file"]
        source = info["source"]
        final_file = info["final_file"]
        accuracy = info.get("policy_accuracy_pct", "N/A")
        binary = info.get("binary_name", "unknown")

        lines.append(f"// {'─' * 72}")
        lines.append(f"// Segment {idx:02d}: {seg_key}")
        lines.append(f"//   target_file : {target}")
        lines.append(f"//   binary      : {binary}")
        lines.append(f"//   accuracy    : {accuracy}%")
        lines.append(f"//   source      : {final_file}")
        lines.append(f"// {'─' * 72}")
        lines.append(f"#if {guard}")
        lines.append("")
        lines.append(source.rstrip())
        lines.append("")
        lines.append(f"#endif // {guard}")
        lines.append("")

    return "\n".join(lines)


def _build_run_script(
    segment_sources: dict[str, dict],
    stitched_dir: Path,
    benchmark_name: str,
) -> str:
    """
    Generate a shell script that builds each segment's binary from the saved
    individual source files and optionally runs them under ``perf stat``.
    """
    lines: list[str] = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        f'# Build & run script for stitched benchmark: {benchmark_name}',
        f'# Generated by stitch_segments.py',
        f'SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"',
        "",
    ]

    # Group segments by build_dir + binary for efficiency
    for seg_key, info in segment_sources.items():
        idx = info["index"]
        target = info["target_file"]
        build_dir = info.get("build_dir", "")
        binary_path = info.get("binary_path", "")
        binary_name = info.get("binary_name", "unknown")
        microbenchmark = info.get("chosen_microbenchmark", "")
        live_source = info.get("live_source_file", "")
        seg_source = f"${{SCRIPT_DIR}}/segment_{idx:02d}.cpp"

        lines.append(f"# ── Segment {idx:02d}: {target} ──")
        if live_source and build_dir and binary_path and microbenchmark:
            quoted_live_source = shlex.quote(str(live_source))
            quoted_build_dir = shlex.quote(str(build_dir))
            quoted_binary_name = shlex.quote(str(binary_name))
            quoted_binary_path = shlex.quote(str(binary_path))
            quoted_regex = shlex.quote(f"^{microbenchmark}$")
            lines.append(f"echo 'Building segment {idx:02d} ({binary_name})...'")
            lines.append("(")
            lines.append("  backup_file=\"$(mktemp)\"")
            lines.append(f"  cp -- {quoted_live_source} \"${{backup_file}}\"")
            lines.append(f"  trap 'cp -- \"${{backup_file}}\" {quoted_live_source}; rm -f -- \"${{backup_file}}\"' EXIT")
            lines.append(f"  cp -- {seg_source} {quoted_live_source}")
            lines.append(
                f"  cmake --build {quoted_build_dir} --target {quoted_binary_name} -- -j$(nproc)"
            )
            lines.append(f"  echo 'Running segment {idx:02d}: {microbenchmark}...'")
            lines.append(
                f"  sudo perf stat -a -C 2 -- taskset -c 2 {quoted_binary_path} "
                f"--benchmark --bm_regex {quoted_regex}"
            )
            lines.append(")")
            lines.append("")
        else:
            lines.append(f"echo 'Segment {idx:02d}: no build info available (manual assembly required)'")
            lines.append(f"# Source: {seg_source}")
            lines.append("")

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Stitch per-segment C++ sources into a combined file"
    )
    parser.add_argument(
        "--replacements-json",
        required=True,
        help="Path to the segment_replacements.json produced by cloud_segment_frontend.py",
    )
    parser.add_argument(
        "--compile",
        action="store_true",
        help="Attempt to compile the stitched file (best-effort, requires framework headers)",
    )
    args = parser.parse_args()

    replacements_path = Path(args.replacements_json)
    if not replacements_path.is_file():
        print(f"[stitch] Replacements JSON not found: {replacements_path}")
        return 1

    data = json.loads(replacements_path.read_text(encoding="utf-8"))
    output_dir = replacements_path.parent
    stitched_dir = output_dir / "stitched"
    stitched_dir.mkdir(parents=True, exist_ok=True)

    segment_results = data.get("segment_results", {})
    if not segment_results:
        print("[stitch] No segment results found in replacements JSON")
        return 0

    # ── Collect per-segment sources ──────────────────────────────────────
    segment_sources: dict[str, dict] = OrderedDict()
    skipped = []
    for seg_key in sorted(segment_results.keys(), key=_segment_sort_key):
        seg = segment_results[seg_key]
        if seg.get("status") != "ok":
            skipped.append((seg_key, "status != ok"))
            continue

        source = _read_segment_source(seg)
        if source is None:
            skipped.append((seg_key, "no compile_record.final_file"))
            continue

        cr = seg.get("compile_record") or {}
        idx = seg.get("segment_index", _segment_sort_key(seg_key))
        segment_sources[seg_key] = {
            "index": idx,
            "source": source,
            "target_file": seg.get("target_file", "unknown"),
            "build_dir": seg.get("build_dir", ""),
            "binary_path": seg.get("binary_path", ""),
            "binary_name": seg.get("binary_name", "unknown"),
            "chosen_microbenchmark": seg.get("chosen_microbenchmark", ""),
            "final_file": cr.get("final_file", ""),
            "live_source_file": cr.get("live_source_file", ""),
            "policy_accuracy_pct": seg.get("policy_accuracy_pct"),
        }

    if not segment_sources:
        print("[stitch] No segments with compile records found — nothing to stitch")
        if skipped:
            for sk, reason in skipped:
                print(f"  {sk}: {reason}")
        return 0

    # ── Write individual segment files ───────────────────────────────────
    individual_files = {}
    for seg_key, info in segment_sources.items():
        idx = info["index"]
        seg_path = stitched_dir / f"segment_{idx:02d}.cpp"
        seg_path.write_text(info["source"], encoding="utf-8")
        individual_files[seg_key] = str(seg_path)
        print(f"[stitch]   {seg_key} -> {seg_path.name}  ({info['target_file']})")

    # ── Derive benchmark name ────────────────────────────────────────────
    source_json = data.get("source_cloud_json", "benchmark")
    benchmark_name = Path(source_json).stem
    # strip common suffixes
    for suffix in ("_feature_extraction", "_segment_replacements"):
        if benchmark_name.endswith(suffix):
            benchmark_name = benchmark_name[: -len(suffix)]

    # ── Write combined stitched file ─────────────────────────────────────
    combined_source = _build_combined_source(segment_sources, benchmark_name)
    combined_path = stitched_dir / f"{benchmark_name}_stitched.cpp"
    combined_path.write_text(combined_source, encoding="utf-8")
    print(f"[stitch] Combined: {combined_path}")
    print(f"[stitch]   {len(segment_sources)} segments, {len(combined_source)} bytes")

    # ── Write build/run helper script ────────────────────────────────────
    run_script = _build_run_script(segment_sources, stitched_dir, benchmark_name)
    run_script_path = stitched_dir / "run_stitched.sh"
    run_script_path.write_text(run_script, encoding="utf-8")
    run_script_path.chmod(0o755)
    print(f"[stitch] Run script: {run_script_path}")

    # ── Optional: attempt compilation ────────────────────────────────────
    compile_result = None
    if args.compile:
        for seg_key, info in segment_sources.items():
            idx = info["index"]
            build_dir = info.get("build_dir")
            binary_name = info.get("binary_name")
            if not build_dir or not binary_name:
                continue
            print(f"[stitch] Compiling segment {idx:02d} ({binary_name})...")
            try:
                cp = subprocess.run(
                    ["cmake", "--build", build_dir, "--target", binary_name, "--", f"-j{os.cpu_count() or 4}"],
                    capture_output=True,
                    text=True,
                    timeout=300,
                )
                if cp.returncode == 0:
                    print(f"[stitch]   segment {idx:02d}: OK")
                else:
                    print(f"[stitch]   segment {idx:02d}: FAILED (rc={cp.returncode})")
                    print(cp.stderr[:500] if cp.stderr else "(no stderr)")
                compile_result = compile_result or {}
                compile_result[seg_key] = {
                    "success": cp.returncode == 0,
                    "returncode": cp.returncode,
                }
            except Exception as e:
                print(f"[stitch]   segment {idx:02d}: compile error: {e}")

    # ── Update replacements JSON with stitching output ───────────────────
    stitching_output = {
        "stitched_at_utc": datetime.now(timezone.utc).isoformat(),
        "stitched_file": str(combined_path),
        "stitched_file_bytes": len(combined_source),
        "run_script": str(run_script_path),
        "segment_count": len(segment_sources),
        "segments_stitched": sorted(segment_sources.keys()),
        "segments_skipped": [{"segment": sk, "reason": reason} for sk, reason in skipped],
        "individual_files": individual_files,
    }
    if compile_result:
        stitching_output["compile_result"] = compile_result

    data["stitching_output"] = stitching_output
    replacements_path.write_text(
        json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print(f"[stitch] Updated: {replacements_path}")

    # ── Summary ──────────────────────────────────────────────────────────
    print(f"\n[stitch] Done: {len(segment_sources)} segments stitched")
    if skipped:
        print(f"[stitch] Skipped: {len(skipped)} segments")
        for sk, reason in skipped:
            print(f"  {sk}: {reason}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
